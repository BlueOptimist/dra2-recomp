// Writes a C header for compiling the decompiled code: every data type in the program (resource structs, class
// structs, vtables, analyzer-created types) plus a prototype for every function, using C-safe names
// (Class::method -> Class__method).
// Args: <program.h>
// @category Digimon
import java.io.PrintWriter;
import java.io.StringWriter;

import ghidra.app.script.GhidraScript;
import ghidra.program.model.data.DataType;
import ghidra.program.model.data.DataTypeManager;
import ghidra.program.model.data.DataTypeWriter;
import ghidra.program.model.listing.Function;
import ghidra.program.model.listing.Parameter;

public class ExportHeader extends GhidraScript {
	static String cName(String qualified) {
		return qualified.replace("::", "__").replaceAll("[^A-Za-z0-9_]", "_");
	}

	static String typeName(DataType dt) {
		return dt.getDisplayName().replace("::", "__");
	}

	@Override
	protected void run() throws Exception {
		DataTypeManager dtm = currentProgram.getDataTypeManager();
		try (PrintWriter out = new PrintWriter(getScriptArgs()[0])) {
			out.println("/* Generated by tools/ghidra_scripts/ExportHeader.java from the Ghidra project. Do not edit. */");
			out.println("#ifndef DRA2_PROGRAM_H\n#define DRA2_PROGRAM_H\n#include \"ghidra_types.h\"\n");
			StringWriter types = new StringWriter();
			DataTypeWriter dtw = new DataTypeWriter(dtm, types, false);
			dtw.write(dtm, monitor);
			// The type writer names unnamed filler bytes "field12_0x3c"; the decompiler refers to them as "field_0x3c".
			// Only one-byte "undefined" filler is renamed: inferred fields keep their real names (e.g. field48_0x3c).
			// Also drop bare type names the writer prints for types it can't express (e.g. "float10" alone).
			out.println(types.toString().replaceAll("(?m)^(\\s+undefined\\s+)field\\d+_0x", "$1field_0x")
					.replaceAll("(?m)^[A-Za-z_]\\w*\\s*$", ""));
			// Function-definition types: the writer inlines them into structs, but the decompiled code also names
			// them (locals, casts), so emit a typedef for each.
			out.println("\n/* ---- function types ---- */");
			int defs = 0;
			String typesText = types.toString();
			java.util.Set<String> typedefNames = new java.util.HashSet<>();
			for (java.util.Iterator<DataType> it = dtm.getAllDataTypes(); it.hasNext();) {
				DataType dt = it.next();
				// same name in two categories (or already a typedef from the type writer): keep the first
				if (!(dt instanceof ghidra.program.model.data.FunctionDefinition) || !typedefNames.add(cName(dt.getName())) ||
					java.util.regex.Pattern.compile("\\b" + java.util.regex.Pattern.quote(cName(dt.getName())) + "\\b")
							.matcher(typesText).find()) {
					continue;
				}
				ghidra.program.model.data.FunctionDefinition fd = (ghidra.program.model.data.FunctionDefinition) dt;
				StringBuilder sb = new StringBuilder("typedef ");
				sb.append(typeName(fd.getReturnType())).append(' ');
				String cc = fd.getCallingConventionName();
				if (cc != null && cc.startsWith("__")) {
					sb.append(cc).append(' ');
				}
				sb.append(cName(fd.getName())).append('(');
				ghidra.program.model.data.ParameterDefinition[] ps = fd.getArguments();
				for (int i = 0; i < ps.length; i++) {
					if (i > 0) {
						sb.append(", ");
					}
					sb.append(typeName(ps[i].getDataType())).append(' ').append(cName(ps[i].getName()));
				}
				if (fd.hasVarArgs()) {
					sb.append(ps.length > 0 ? ", ..." : "...");
				}
				else if (ps.length == 0) {
					sb.append("void");
				}
				sb.append(");");
				out.println(sb);
				defs++;
			}
			println("wrote " + defs + " function type typedefs");
			out.println("\n/* ---- function prototypes ---- */");
			int n = 0;
			for (Function f : currentProgram.getFunctionManager().getFunctions(true)) {
				StringBuilder sb = new StringBuilder();
				sb.append(typeName(f.getReturnType())).append(' ');
				String cc = f.getCallingConventionName();
				if (cc != null && cc.startsWith("__")) {
					sb.append(cc).append(' ');
				}
				sb.append(cName(f.getName(true))).append('(');
				Parameter[] ps = f.getParameters();
				for (int i = 0; i < ps.length; i++) {
					if (i > 0) {
						sb.append(", ");
					}
					sb.append(typeName(ps[i].getDataType())).append(' ').append(cName(ps[i].getName()));
				}
				if (f.hasVarArgs()) {
					sb.append(ps.length > 0 ? ", ..." : "...");
				}
				else if (ps.length == 0) {
					sb.append("void");
				}
				sb.append(");");
				out.println(sb);
				n++;
			}
			out.println("\n#endif");
			println("wrote " + n + " prototypes");
		}
	}
}

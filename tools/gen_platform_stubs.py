"""Generate weak stand-ins for every Xbox system symbol the game still needs: decomp/port/xbox_stubs.c.

Usage: python gen_platform_stubs.py <decomp_dir>

Reads build/data/data_report.txt (tools/gen_data.py) for what is still undefined, and build/program.h for each
function's exact prototype (calling convention and parameters decide the decorated name the game links against).
  - Xbox API functions (D3D8__, DSOUND__, XAPILIB__, XGRAPHC__/XGRAPHICS__, and unnamed FUN_s in the XDK sections and
    lib/xapi) get a body that reports the call once through port_todo() and returns 0
  - Xbox API data and data labels inside the XDK sections get zero-filled storage
Every definition is weak: a real implementation anywhere in decomp/port/ replaces it at link time, so the platform
layer can be written one function at a time.
"""
import os
import re
import sys

API = re.compile(r"^(?:D3D8|DSOUND|XAPILIB|XGRAPHC|XGRAPHICS|D3DX)__\w+$")
XDK_START = 0x217200  # D3D, D3DX, XGRPH, DSOUND, XPP, DOLBY sections follow .text
XAPI_RANGES = [(0x1256F0, 0x12F600), (0x1EBD00, 0x1EDA20), (0x1F9DA0, 0x1F9DB3)]
FLOAT_TYPES = {"float", "double", "float10"}


def is_xdk_address(name):
    m = re.search(r"_([0-9a-f]{8})$", name)
    if not m:
        return False
    a = int(m.group(1), 16)
    return a >= XDK_START or any(lo <= a < hi for lo, hi in XAPI_RANGES)


def main():
    decomp = sys.argv[1]
    build = os.path.join(decomp, "build")
    report = open(os.path.join(build, "data", "data_report.txt"), encoding="latin-1").read().splitlines()
    still = [l.strip() for l in report if re.match(r"^  \S+$", l)]
    program = open(os.path.join(build, "program.h"), encoding="latin-1").read()
    protos = {}
    for line in program.splitlines():
        m = re.match(r"^([\w ]+?[\s*]+)(?:__(?:stdcall|cdecl|fastcall|thiscall)\s+)?(\w+)\((.*)\);$", line)
        if m and m.group(2) not in protos:
            protos[m.group(2)] = line

    funcs, datas = [], []
    for name in still:
        api = API.match(name)
        code = re.match(r"^(?:thunk_)?FUN_[0-9a-f]{8}$", name) and is_xdk_address(name)
        label = re.match(r"^_*(?:DAT|PTR|UNK)_[0-9a-f]{8}$", name) and is_xdk_address(name)
        if (api or code) and name in protos:
            funcs.append(name)
        elif api or label:
            datas.append(name)

    out = ["/* Generated by tools/gen_platform_stubs.py: weak stand-ins for the Xbox system symbols the game uses.",
           " * Write the real implementation anywhere in decomp/port/ (same name and prototype as in build/program.h)",
           " * and it replaces the stub here at link time. Do not edit this file; regenerate it. */",
           '#include "program_types.h"', "",
           "void port_todo(const char *name);", "",
           "/* ---- data the game reads or writes inside the Xbox libraries (zero-filled; 64 bytes each) ---- */"]
    for d in sorted(datas):
        out.append(f"__attribute__((weak)) unsigned char {d}[64];")
    out.append("")
    groups = {}
    for f in funcs:
        groups.setdefault(f.split("__")[0] if "__" in f else "XDK library (unnamed)", []).append(f)
    for group in sorted(groups):
        out.append(f"/* ---- {group} ---- */")
        for f in sorted(groups[group]):
            proto = protos[f].rstrip(";")
            ret = re.match(r"^([\w ]+?[\s*]+)(?:__\w+\s+)?\w+\(", proto).group(1).strip()
            # parameters need names for a definition; Ghidra's prototypes already have them (param_N)
            body = f'port_todo("{f}");'
            if ret != "void":
                body += " return 0;"
            out.append(f"__attribute__((weak)) {proto} {{ {body} }}")
        out.append("")

    path = os.path.join(decomp, "port", "xbox_stubs.c")
    with open(path, "w", encoding="latin-1") as f:
        f.write("\n".join(out))
    print(f"wrote {path}: {len(funcs)} function stubs, {len(datas)} data symbols")
    for group in sorted(groups):
        print(f"  {len(groups[group]):4}  {group}")


if __name__ == "__main__":
    main()
